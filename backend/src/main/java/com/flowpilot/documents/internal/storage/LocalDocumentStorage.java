package com.flowpilot.documents.internal.storage;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;

import org.springframework.stereotype.Component;

import com.flowpilot.documents.internal.DocumentProperties;

/** Stores files on a local directory. In Docker this directory is a volume shared by all replicas. */
@Component
class LocalDocumentStorage implements DocumentStorage {

    private final Path root;

    LocalDocumentStorage(DocumentProperties properties) {
        this.root = properties.storagePath().toAbsolutePath().normalize();
    }

    @Override
    public StoredFile store(String storageKey, InputStream content, long maxBytes) throws IOException {
        Path target = resolve(storageKey);
        Files.createDirectories(target.getParent());
        MessageDigest digest = newSha256();
        long total = 0;
        byte[] buffer = new byte[8192];
        try (OutputStream out = Files.newOutputStream(target, StandardOpenOption.CREATE_NEW)) {
            int read;
            while ((read = content.read(buffer)) != -1) {
                total += read;
                if (total > maxBytes) {
                    throw new FileTooLargeException(maxBytes);
                }
                digest.update(buffer, 0, read);
                out.write(buffer, 0, read);
            }
        } catch (IOException | RuntimeException e) {
            Files.deleteIfExists(target);   // never leave a partial file behind
            throw e;
        }
        return new StoredFile(storageKey, total, digest.digest());
    }

    @Override
    public InputStream open(String storageKey) throws IOException {
        return Files.newInputStream(resolve(storageKey));
    }

    @Override
    public void delete(String storageKey) throws IOException {
        Files.deleteIfExists(resolve(storageKey));
    }

    /** The key is generated by the application, but we still refuse anything that escapes the root directory. */
    private Path resolve(String storageKey) {
        Path path = root.resolve(storageKey).normalize();
        if (!path.startsWith(root) || path.equals(root)) {
            throw new IllegalArgumentException("Invalid storage key.");
        }
        return path;
    }

    private static MessageDigest newSha256() {
        try {
            return MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 is not available.", e);
        }
    }
}